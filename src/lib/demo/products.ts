export const cardOf = (p: Product): CardData => ({
  id: p.id,
  name: p.name,
  cat: p.cat,
  price: p.price,
  was: p.was,
  rating: p.rating,
  count: p.count,
  photo: p.photo,
  badge: p.badge,
});

export const cards: CardData[] = products.map(cardOf);

export function productById(id: string) {
  return products.find((p) => p.id === id);
}

/** Produits associés : d'abord la même catégorie, puis le reste, quatre au total. */
export function relatedTo(id: string): CardData[] {
  const p = productById(id);
  if (!p) return [];
  const same = products.filter((x) => x.cat === p.cat && x.id !== id);
  const others = products.filter((x) => x.cat !== p.cat && x.id !== id);
  return [...same, ...others].slice(0, 4).map(cardOf);
}

export function reviewsFor(id: string): Review[] {
  return reviews.filter((r) => r.productId === id);
}

export function homeReviews(): Review[] {
  return homeReviewIds.map((id) => {
    const r = reviews.find((x) => x.id === id)!;
    return { ...r, productName: productById(r.productId)!.name };
  });
}
